#!/usr/bin/env python3
"""Build Data/Dungeons.lua from the Wowhead exports and the client's encounter table.

Inputs (all in tools/data/):
  dungeons.json                  every live dungeon: key, name, map ID, level, Wowhead URL
                                 (generated by tools/make_dungeon_list.py)
  wowhead/<key>.json             one export per dungeon (tools/wowhead.py import)
  gamedata/DungeonEncounter.csv  boss encounters per instance map (from the game client)
  npc_aliases.json               NPC name -> encounter name, for adds whose loot belongs to a boss
  excluded_items.json            item IDs to drop (e.g. no transmog appearance in the client)

An item is kept if it
  - has a transmog appearance,
  - is Uncommon (2) or better,
  - drops from an NPC that matches a boss encounter of the dungeon (directly or via alias).
Binding (bind-on-pickup) is not in the Wowhead data; check it in game with /fj probe data.
Dungeons are ordered by level, then name (as in dungeons.json).

Usage: python3 tools/build_data.py            # writes Data/Dungeons.lua, prints a summary
       python3 tools/build_data.py --check    # exits 1 if Data/Dungeons.lua is out of date
"""

import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "tools" / "data"
OUTPUT = ROOT / "Data" / "Dungeons.lua"
MIN_QUALITY = 2  # Uncommon
NO_TRANSMOG_SLOTS = {24, 25}  # Wowhead slot IDs: ammo, thrown (no appearance in the Forever client)
NORMAL_DIFFICULTIES = {0, 1}  # other DifficultyIDs are variants of the same map (e.g. Season of Discovery)


class BuildError(Exception):
    pass


def load_json(name, default=None):
    path = DATA / name
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def without_comments(mapping):
    return {k: v for k, v in (mapping or {}).items() if not k.startswith("_")}


def load_encounters():
    """Boss encounters per map, normal difficulty only, in dungeon order."""
    all_by_map = defaultdict(list)
    with open(DATA / "gamedata" / "DungeonEncounter.csv", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            all_by_map[int(row["MapID"])].append({
                "id": int(row["ID"]),
                "name": row["Name_lang"],
                "order": int(row["OrderIndex"]),
                "difficulty": int(row["DifficultyID"]),
            })
    by_map = {}
    for map_id, encounters in all_by_map.items():
        normal = [e for e in encounters if e["difficulty"] in NORMAL_DIFFICULTIES]
        chosen, seen = [], set()
        for e in sorted(normal or encounters, key=lambda e: (e["order"], e["id"])):
            if e["name"] not in seen:  # one entry per boss
                seen.add(e["name"])
                chosen.append(e)
        by_map[map_id] = chosen
    return by_map


def table(export, kind, table_id=None):
    for t in export.get("tables", []):
        if t.get("kind") == kind and (table_id is None or t.get("id") == table_id):
            return t.get("rows", [])
    return []


def best_matching_map(export, encounters_by_map, aliases):
    """The instance map whose boss encounters best match the NPCs on the Wowhead page."""
    npc_names = {r.get("name") for r in table(export, "npc")}
    npc_names |= {s.get("n") for r in table(export, "item", "drops") for s in r.get("sourcemore") or []}
    npc_names |= {aliases[n] for n in npc_names if n in aliases}
    best, best_score = None, 0
    for map_id, encounters in encounters_by_map.items():
        score = sum(1 for e in encounters if e["name"] in npc_names)
        if score > best_score:
            best, best_score = map_id, score
    return best, best_score


def build_dungeon(dungeon, export, encounters_by_map, aliases, excluded_ids, log):
    map_id = dungeon["mapID"]
    encounters = encounters_by_map.get(map_id, [])
    found_map, score = best_matching_map(export, encounters_by_map, aliases)
    log.append(f"{dungeon['key']}: {dungeon['name']} (map {map_id}), {score}/{len(encounters)} encounters matched, "
               f"exported {str(export.get('exportedAt'))[:10]}")
    if found_map is None:
        raise BuildError(f"{dungeon['key']}: no boss of this dungeon appears in the Wowhead export "
                         f"(Wowhead's data for it may still be too thin)")
    if found_map != map_id:
        raise BuildError(f"{dungeon['key']}: the Wowhead export matches map {found_map}, not {map_id}. "
                         f"Wrong page? Check the zone in tools/data/dungeons.json.")

    by_name = {e["name"]: e for e in encounters}
    items_by_boss = {e["id"]: [] for e in encounters}
    excluded = []
    for item in table(export, "item", "drops"):
        label = f"{item['id']} {item.get('name')}"
        if item["id"] in excluded_ids:
            excluded.append(f"{label}: excluded_items.json")
            continue
        if not item.get("appearances"):
            excluded.append(f"{label}: no appearance")
            continue
        if item.get("slot") in NO_TRANSMOG_SLOTS:
            excluded.append(f"{label}: slot {item.get('slot')} has no transmog")
            continue
        if (item.get("quality") or 0) < MIN_QUALITY:
            excluded.append(f"{label}: quality {item.get('quality')}")
            continue
        boss = None
        for src in item.get("sourcemore") or []:
            npc = src.get("n")
            boss = by_name.get(npc) or by_name.get(aliases.get(npc))
            if boss:
                break
        if not boss:
            sources = ", ".join(s.get("n", "?") for s in item.get("sourcemore") or []) or "unknown source"
            excluded.append(f"{label}: not a boss drop ({sources})")
            continue
        items_by_boss[boss["id"]].append(item["id"])

    for line in excluded:
        log.append("   excluded " + line)
    for e in encounters:
        if not items_by_boss[e["id"]]:
            log.append(f"   warning: boss {e['name']} ({e['id']}) has no items yet (left out)")

    return {
        "key": dungeon["key"],
        "name": dungeon["name"],
        "level": dungeon["level"],
        "mapID": map_id,
        "wowheadZone": dungeon["wowheadZone"],
        # Bosses without known drops are left out until Wowhead has data for them.
        "bosses": [
            {"name": e["name"], "encounterID": e["id"], "items": sorted(items_by_boss[e["id"]])}
            for e in encounters if items_by_boss[e["id"]]
        ],
    }


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(dungeons):
    out = [
        "-- Generated by tools/build_data.py. Do not edit by hand; edit tools/data/ and re-run.",
        "local _, ns = ...",
        "",
        "ns.Dungeons = {",
    ]
    for d in dungeons:
        out.append("\t{")
        out.append(f"\t\tkey = {lua_string(d['key'])},")
        out.append(f"\t\tname = {lua_string(d['name'])},")
        out.append(f"\t\tlevel = {d['level']},")
        out.append(f"\t\tmapID = {d['mapID']},")
        out.append(f"\t\twowheadZone = {d['wowheadZone']},")
        out.append("\t\tbosses = {")
        for b in d["bosses"]:
            items = ", ".join(str(i) for i in b["items"])
            out.append(f"\t\t\t{{ name = {lua_string(b['name'])}, encounterID = {b['encounterID']}, items = {{ {items} }} }},")
        out.append("\t\t},")
        out.append("\t},")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if Data/Dungeons.lua is out of date")
    args = parser.parse_args()

    dungeon_list = load_json("dungeons.json")
    encounters_by_map = load_encounters()
    aliases = without_comments(load_json("npc_aliases.json", {}))
    excluded_ids = {int(k) for k in without_comments(load_json("excluded_items.json", {}))}

    known_keys = {d["key"] for d in dungeon_list}
    for path in (DATA / "wowhead").glob("*.json"):
        if path.stem not in known_keys:
            raise SystemExit(f"tools/data/wowhead/{path.name}: not a dungeon key from tools/data/dungeons.json")

    log, dungeons, missing, errors = [], [], [], []
    for dungeon in dungeon_list:  # already ordered by level, then name
        path = DATA / "wowhead" / f"{dungeon['key']}.json"
        if not path.exists():
            missing.append(dungeon)
            continue
        export = json.loads(path.read_text(encoding="utf-8"))
        try:
            dungeons.append(build_dungeon(dungeon, export, encounters_by_map, aliases, excluded_ids, log))
        except BuildError as err:
            errors.append(str(err))

    text = render(dungeons)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("Data/Dungeons.lua is out of date: run python3 tools/build_data.py", file=sys.stderr)
            return 1
        print("Data/Dungeons.lua is up to date")
        return 0

    OUTPUT.write_text(text, encoding="utf-8")
    print("\n".join(log))
    if missing:
        print(f"{len(missing)} dungeons without a Wowhead export yet: " + ", ".join(d["name"] for d in missing))
    total = sum(len(b["items"]) for d in dungeons for b in d["bosses"])
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(dungeons)} dungeons, {total} items")
    for err in errors:
        print("ERROR (dungeon skipped): " + err)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
